import { readFile, mkdir, rm } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { format } from "prettier";
import { brands, type IllustrationManifest } from "../src/types.js";
import {
  projectRoot,
  readJson,
  palettes,
  stableJson,
  sha256,
  writeOutput,
  listFiles,
  type Config,
  type SourceLock,
} from "./lib/project.js";
import { validateConfig } from "./lib/validate.js";
import { jsx, mapPaints, serialize, optimizeIllustration } from "./lib/svg.js";
import { optimizeEmbeddedImages } from "./lib/images.js";

export async function generate(
  check = false,
  input: {
    config?: Config;
    lock?: SourceLock;
    sources?: ReadonlyMap<string, string>;
    files?: ReadonlyMap<string, string>;
  } = {},
) {
  const config = input.config ?? (await readJson<Config>("figma.config.json"));
  const colors = await palettes();
  validateConfig(config, colors);
  const lock = input.lock ?? (await readJson<SourceLock>(".figma/lock.json"));
  if (
    lock.schemaVersion !== 1 ||
    lock.assets.length !== config.illustrations.length ||
    new Set(lock.assets.map((a) => a.path)).size !== lock.assets.length
  ) {
    throw new Error("Invalid source lock.");
  }
  const manifest: IllustrationManifest = {
    schemaVersion: 1,
    figmaFileKey: config.fileKey,
    figmaVersion: lock.figmaVersion,
    illustrations: [],
  };
  const expected = new Set<string>();
  const outputs = new Map<string, string | Buffer>([
    ...(input.files ?? []),
    ...(input.sources ?? []),
  ]);
  const optimization: Array<{ slug: string; before: number; after: number }> =
    [];
  for (const entry of config.illustrations) {
    expected.add(entry.original);
  }
  const output = (file: string, value: string | Buffer) => {
    expected.add(file);
    outputs.set(file, value);
  };
  for (const source of config.illustrations) {
    const original =
      input.sources?.get(source.original) ??
      (await readFile(path.join(projectRoot, source.original), "utf8"));
    const locked = lock.assets.find((a) => a.path === source.original);
    if (
      !locked ||
      locked.nodeId !== source.nodeId ||
      locked.sha256 !== sha256(original)
    ) {
      throw new Error("Source differs from lock: " + source.original);
    }
    const mapped = mapPaints(original, source.paints);
    const key = source.category + "/" + source.slug;
    await optimizeEmbeddedImages(mapped.root, mapped.width, mapped.height);
    const optimized = optimizeIllustration(mapped.root);
    optimization.push({
      slug: source.slug,
      before: Buffer.byteLength(serialize(mapped.root)),
      after: Buffer.byteLength(serialize(optimized)),
    });
    const name = source.slug
      .split("-")
      .map((s) => s[0]!.toUpperCase() + s.slice(1))
      .join("");
    const drawing = jsx(optimized);
    const module =
      "'use client';\n/** Generated by npm run generate. */\nimport { createIllustration } from '../runtime.js';\nconst " +
      name +
      " = createIllustration({slug:" +
      JSON.stringify(source.slug) +
      ",name:" +
      JSON.stringify(name) +
      ",width:" +
      mapped.width +
      ",height:" +
      mapped.height +
      ",draw:(" +
      (drawing.includes("prefix") ? "prefix" : "") +
      ")=>(" +
      drawing +
      ")});\nexport { " +
      name +
      " };\nexport default " +
      name +
      ";\n";
    output(
      "src/react/" + key + ".tsx",
      await format(module, { parser: "typescript" }),
    );
    const entry: IllustrationManifest["illustrations"][number] = {
      slug: source.slug,
      name: source.name,
      category: source.category,
      nodeId: source.nodeId,
      width: mapped.width,
      height: mapped.height,
      page: source.page ?? "Components",
      pageId: source.pageId ?? config.rootNodeId,
      status: source.status ?? "component",
      supportedSurfaces: {
        dnb: ["light", "dark"],
        sbanken: ["light", "dark"],
        eiendom: ["light", "dark"],
        carnegie: ["light"],
      },
      roles: mapped.roles,
    };
    for (const brand of brands) {
      const palette = colors[brand];
      for (const role of mapped.roles) {
        if (!palette.roles[role]) {
          throw new Error("Missing role: " + brand + "/" + role);
        }
      }
    }
    manifest.illustrations.push(entry);
  }
  const css = ["/* Generated from tokens/*.json. */", ":where(:root) {"];
  for (const brand of brands) {
    for (const [name, value] of Object.entries(colors[brand].foundations)) {
      css.push("  " + name + ": " + value + ";");
    }
  }
  css.push(
    "}",
    ".dnb-illustration { display: inline-block; max-width: 100%; height: auto; vertical-align: middle; }",
  );
  for (const brand of brands) {
    const palette = colors[brand];
    const selector =
      '.dnb-illustration[data-illustration-brand="' + brand + '"]';
    css.push(selector + " {");
    for (const [role, ref] of Object.entries(palette.roles)) {
      css.push("  --illustration-" + role + ": var(" + ref + ");");
    }
    css.push("}");
    if (palette.supportedSurfaces.includes("dark")) {
      css.push(selector + '[data-illustration-surface="dark"] {');
      for (const [role, ref] of Object.entries(palette.darkRoles)) {
        css.push("  --illustration-" + role + ": var(" + ref + ");");
      }
      css.push("}");
    }
  }
  output(
    "styles/illustrations.css",
    await format(css.join("\n"), { parser: "css" }),
  );
  output(
    "manifest.json",
    await format(stableJson(manifest), { parser: "json" }),
  );
  const index = [
    "export { IllustrationProvider } from './runtime.js';",
    "export type { IllustrationProps, IllustrationTheme } from './runtime.js';",
  ];
  for (const entry of manifest.illustrations) {
    const name = entry.slug
      .split("-")
      .map((s) => s[0]!.toUpperCase() + s.slice(1))
      .join("");
    index.push(
      "export { default as " +
        name +
        ' } from "./' +
        entry.category +
        "/" +
        entry.slug +
        '.js";',
    );
  }
  output(
    "src/react/index.ts",
    await format(index.join("\n"), { parser: "typescript" }),
  );
  const registry = manifest.illustrations.map((entry) => {
    const name = entry.slug
      .split("-")
      .map((s) => s[0]!.toUpperCase() + s.slice(1))
      .join("");
    return { entry, name };
  });
  output(
    "site/components.generated.ts",
    await format(
      'import {lazy} from "react";\nexport default {\n' +
        registry
          .map(
            ({ entry }) =>
              JSON.stringify(entry.slug) +
              ':lazy(()=>import("../src/react/' +
              entry.category +
              "/" +
              entry.slug +
              '.js"))',
          )
          .join(",\n") +
        "\n};",
      { parser: "typescript" },
    ),
  );
  const obsolete: string[] = [];
  for (const directory of ["sources", "styles", "src/react"]) {
    await mkdir(path.join(projectRoot, directory), { recursive: true });
    for (const file of await listFiles(path.join(projectRoot, directory))) {
      const relative = path.relative(projectRoot, file);
      if (relative !== "src/react/runtime.tsx" && !expected.has(relative)) {
        if (check || directory === "sources") {
          throw new Error("Orphaned generated file: " + relative);
        }
        obsolete.push(file);
      }
    }
  }
  if (!check) {
    outputs.set(
      ".figma/optimization.json",
      await format(
        stableJson({
          engine: "svgo",
          version: "4.1.0",
          sourceBytes: optimization.reduce((n, r) => n + r.before, 0),
          optimizedBytes: optimization.reduce((n, r) => n + r.after, 0),
          illustrations: optimization,
        }),
        { parser: "json" },
      ),
    );
  }
  // Validate and render the complete batch before changing any source files.
  for (const [file, value] of outputs) {
    await writeOutput(file, value, check);
  }
  for (const file of obsolete) {
    await rm(file);
  }
  console.log(
    (check ? "Verified" : "Generated") +
      " " +
      manifest.illustrations.length +
      " illustrations.",
  );
}
if (
  process.argv[1] &&
  fileURLToPath(import.meta.url) === path.resolve(process.argv[1])
) {
  await generate(process.argv.includes("--check"));
}
